/* ---------------- TLV ---------------- */

static size_t tlv_add(uint8_t *buf, size_t cap, size_t off, const char *key,
                      const void *val, uint32_t vlen) {
    size_t kl = strlen(key);
    if (kl == 0 || kl > 63) return off;
    if (off + 1 + kl + 4 + vlen > cap) return off;
    buf[off++] = (uint8_t)kl;
    memcpy(buf + off, key, kl);
    off += kl;
    buf[off++] = (uint8_t)(vlen >> 24);
    buf[off++] = (uint8_t)(vlen >> 16);
    buf[off++] = (uint8_t)(vlen >> 8);
    buf[off++] = (uint8_t)vlen;
    if (vlen) memcpy(buf + off, val, vlen);
    return off + vlen;
}

static int tlv_get(const uint8_t *buf, size_t len, const char *key,
                   const uint8_t **val, uint32_t *vlen) {
    size_t kl = strlen(key), off = 0;
    while (off < len) {
        if (off + 1 > len) return -1;
        size_t k = buf[off++];
        if (k == 0 || off + k + 4 > len) return -1;
        int match = (k == kl) && memcmp(buf + off, key, kl) == 0;
        off += k;
        uint32_t vl = ((uint32_t)buf[off] << 24) | ((uint32_t)buf[off + 1] << 16) |
                      ((uint32_t)buf[off + 2] << 8) | buf[off + 3];
        off += 4;
        if (off + vl > len) return -1;
        if (match) {
            *val = buf + off;
            *vlen = vl;
            return 0;
        }
        off += vl;
    }
    return -1;
}

/* ---------------- frames ---------------- */

static void nonce_of(uint8_t n[12], int dir, uint32_t seq) {
    memset(n, 0, 12);
    n[0] = (uint8_t)dir;
    n[8] = (uint8_t)(seq >> 24);
    n[9] = (uint8_t)(seq >> 16);
    n[10] = (uint8_t)(seq >> 8);
    n[11] = (uint8_t)seq;
}

static int seal_frame(int type, uint8_t flags, uint64_t sid, uint32_t seq, int dir,
                      const uint8_t *payload, size_t plen,
                      const uint8_t *key, uint8_t **out, size_t *outlen) {
    uint8_t *buf = (uint8_t *)malloc(HDR + plen + 16);
    if (!buf) return -1;
    memcpy(buf, "BDC2", 4);
    buf[4] = 1;
    buf[5] = (uint8_t)type;
    buf[6] = flags;
    buf[7] = 0;
    for (int i = 0; i < 8; i++) buf[8 + i] = (uint8_t)(sid >> (56 - i * 8));
    buf[16] = (uint8_t)(seq >> 24);
    buf[17] = (uint8_t)(seq >> 16);
    buf[18] = (uint8_t)(seq >> 8);
    buf[19] = (uint8_t)seq;
    if (flags & 1) {
        uint32_t l = (uint32_t)plen;
        buf[20] = (uint8_t)(l >> 24); buf[21] = (uint8_t)(l >> 16);
        buf[22] = (uint8_t)(l >> 8); buf[23] = (uint8_t)l;
        memcpy(buf + HDR, payload, plen);
        *out = buf;
        *outlen = HDR + plen;
        return 0;
    }
    uint32_t l = (uint32_t)plen + 16;
    buf[20] = (uint8_t)(l >> 24); buf[21] = (uint8_t)(l >> 16);
    buf[22] = (uint8_t)(l >> 8); buf[23] = (uint8_t)l;
    uint8_t nonce[12], tag[16];
    nonce_of(nonce, dir, seq);
    aes_gcm_encrypt(key, nonce, buf, HDR, payload, plen, buf + HDR, tag);
    memcpy(buf + HDR + plen, tag, 16);
    *out = buf;
    *outlen = HDR + plen + 16;
    return 0;
}

static int open_frame(uint8_t *buf, size_t len, const uint8_t *key, int dir,
                      int *type, uint64_t *sid, uint32_t *seq,
                      const uint8_t **payload, size_t *plen) {
    if (len < HDR || memcmp(buf, "BDC2", 4) != 0 || buf[4] != 1) return -1;
    *type = buf[5];
    int flags = buf[6];
    *sid = 0;
    for (int i = 0; i < 8; i++) *sid = (*sid << 8) | buf[8 + i];
    *seq = ((uint32_t)buf[16] << 24) | ((uint32_t)buf[17] << 16) |
           ((uint32_t)buf[18] << 8) | buf[19];
    uint32_t l = ((uint32_t)buf[20] << 24) | ((uint32_t)buf[21] << 16) |
                 ((uint32_t)buf[22] << 8) | buf[23];
    if (len != HDR + l) return -1;
    if (flags & 1) {
        *payload = buf + HDR;
        *plen = l;
        return 0;
    }
    if (!key || l < 16) return -1;
    uint8_t nonce[12];
    nonce_of(nonce, dir, *seq);
    if (aes_gcm_decrypt(key, nonce, buf, HDR, buf + HDR, l - 16, buf + HDR,
                        buf + HDR + l - 16) != 0)
        return -1;
    *payload = buf + HDR;
    *plen = l - 16;
    return 0;
}

static int send_msg(ws_conn *c, int type, const uint8_t *payload, size_t plen) {
    uint8_t *frame = NULL;
    size_t flen = 0;
    int rc;
    if (g_send_cs_init) EnterCriticalSection(&g_send_cs);
    g_send_seq++;
    if (seal_frame(type, 0, g_sid, g_send_seq, D_C2S, payload, plen, g_key,
                   &frame, &flen) != 0) {
        if (g_send_cs_init) LeaveCriticalSection(&g_send_cs);
        return -1;
    }
    rc = ws_send(c, 2, frame, flen);
    free(frame);
    if (g_send_cs_init) LeaveCriticalSection(&g_send_cs);
    return rc;
}

/* ---------------- helpers ---------------- */

static void sha_hex(const uint8_t d[32], char out[65]) {
    static const char hx[] = "0123456789abcdef";
    for (int i = 0; i < 32; i++) {
        out[i * 2] = hx[d[i] >> 4];
        out[i * 2 + 1] = hx[d[i] & 15];
    }
    out[64] = 0;
}

static int mkdirs(const char *path) {
    char tmp[MAX_PATH];
    size_t n = strlen(path);
    if (n >= sizeof(tmp)) return -1;
    memcpy(tmp, path, n + 1);
    for (size_t i = 1; i < n; i++) {
        if (tmp[i] == '\\' || tmp[i] == '/') {
            char save = tmp[i];
            tmp[i] = 0;
            CreateDirectoryA(tmp, NULL);
            tmp[i] = save;
        }
    }
    return 0;
}

static void sysinfo(char *out, size_t cap, const char *id) {
    char host[128] = {0};
    DWORD hn = sizeof(host);
    GetComputerNameA(host, &hn);
    OSVERSIONINFOA vi;
    memset(&vi, 0, sizeof(vi));
    vi.dwOSVersionInfoSize = sizeof(vi);
    GetVersionExA(&vi);
    snprintf(out, cap, "id=%s host=%s os=%lu.%lu.%lu arch=%s ver=%s pid=%lu",
             id, host, (unsigned long)vi.dwMajorVersion, (unsigned long)vi.dwMinorVersion,
             (unsigned long)vi.dwBuildNumber, ARCH, CLIENT_VER,
             (unsigned long)GetCurrentProcessId());
}

