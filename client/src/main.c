/* Modules post asynchronous frames (tunnel data / close).  BDC2 v1 has no
 * dedicated tunnel frame type, so they are carried in a NOTICE frame as TLV
 * ("sub"="tunnel"): this keeps the frozen wire format untouched while letting
 * an operator of the merged build demultiplex tunnels. */
void c2_post(u8 type, const void *data, size_t len)
{
    ws_conn *c = g_active_conn;
    uint8_t ftype[8];
    uint8_t *buf;
    size_t off = 0;
    if (!c || !g_send_cs_init || len > (4u * 1024u * 1024u)) return;
    buf = (uint8_t *)malloc(len + 256);
    if (!buf) return;
    snprintf((char *)ftype, sizeof(ftype), "%u", (unsigned)type);
    off = tlv_add(buf, len + 256, off, "sub", "tunnel", 6);
    off = tlv_add(buf, len + 256, off, "ftype", ftype, (uint32_t)strlen((char *)ftype));
    off = tlv_add(buf, len + 256, off, "data", data, (uint32_t)len);
    send_msg(c, 12 /* T_NOTICE */, buf, off);
    free(buf);
}

void c2_request_shutdown(void)
{
    InterlockedExchange(&g_shutdown_req, 1);
}

static void logmsg(const char *fmt, ...) {
    va_list ap;
    va_start(ap, fmt);
    vfprintf(stderr, fmt, ap);
    fprintf(stderr, "\n");
    va_end(ap);
    if (g_logf) {
        va_start(ap, fmt);
        vfprintf(g_logf, fmt, ap);
        fprintf(g_logf, "\n");
        va_end(ap);
        fflush(g_logf);
    }
}

